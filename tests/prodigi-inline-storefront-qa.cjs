const {assert,mount,reset,click,button}=require('./qa/gallery-shop-dom.cjs');
const Storefront=require('../src/components/shop/PhotoProductStorefront.tsx').default;
const Personalization=require('../src/components/shop/PersonalizationShop.tsx').default;
const {publicShopCatalog,defaultPublicOffer}=require('../src/lib/galleries/public-offer.ts');
const catalog={offer:{enabled:true,title:'Sklep',introduction:'Oferta',buttonLabel:'Zdjęcia z galerii',personalizationEnabled:true,personalizationTitle:'Własna fotografia',personalizationIntroduction:'Dodaj fotografię',personalizationButtonLabel:'Własne zdjęcie'},formats:[],delivery:{courier:{enabled:true,amount:2000},locker:{enabled:false,amount:0},pickup:{enabled:false,amount:0}},products:[{id:50,title:'Fine art',price:9900,description:'Papier',minPhotos:1,maxPhotos:1,personalizationEligible:true}]};
const reply=(body,status=200)=>({ok:status<400,status,json:async()=>body});
global.fetch=async url=>url==='/api/shop/catalog'?reply({success:true,catalog}):reply({success:false,error:'Zaloguj się'},401);
(async()=>{
 const spec={version:1,provider:'prodigi',environment:'sandbox',productId:50,sku:'GLOBAL-FAP-11X14',variant:{attributes:{paperType:'EMA'},printAreaSizes:{default:{horizontalResolution:3307,verticalResolution:4192}}},requiredAssets:['default'],shippingMethod:'Budget',ordersEnabled:false,liveQualified:false,destination:'PL'};
 const config={enabled:true,formats:[],delivery:catalog.delivery,publicOffer:{...defaultPublicOffer(),enabled:true,productIds:[50]}};
 const product={...catalog.products[0],prodigi:spec,nphoto_product_id:'PRIVATE-ID',nphoto_url:'PRIVATE-URL'};
 const projected=publicShopCatalog(config,[product]);
 assert.equal(projected.products[0].personalizationEligible,true);
 assert.equal(projected.products[0].prodigi,undefined);
 assert.doesNotMatch(JSON.stringify(projected),/PRIVATE-ID|PRIVATE-URL|GLOBAL-FAP|paperType/);
 assert.equal(publicShopCatalog(config,[{...product,prodigi:{...spec,requiredAssets:['front','back']}}]).products[0].personalizationEligible,false);
 assert.equal(publicShopCatalog(config,[{...product,maxPhotos:2}]).products[0].personalizationEligible,false);
 window.history.replaceState(null,'','/karta-podarunkowa');
 await mount(Storefront,{});
 await click(button('Własne zdjęcie'));
 const section=document.querySelector('#personalizacja-produktu');
 assert.ok(section,'Personalization is embedded in store');
 assert.equal(section.querySelector('h2').textContent,'Fine art');
 await click(section.querySelector('button.bg-stone-900'));
 const link=document.querySelector('a[href^="/logowanie?"]');assert.ok(link);
 const destination=new URLSearchParams(link.getAttribute('href').split('?')[1]).get('returnTo');
 assert.equal(destination,'/karta-podarunkowa?shopProduct=50&shopPersonalize=1#personalizacja-produktu');
 assert.equal(document.querySelector('[aria-modal="true"]'),null);
 await reset();
 global.fetch=async()=>reply({success:true,catalog:null});
 await mount(Personalization,{});
 assert.ok(document.body.textContent.includes('Dodawanie własnych zdjęć jest obecnie niedostępne'));
 await reset();
 global.fetch=async()=>reply({success:true,catalog:{...catalog,products:[]}});
 await mount(Personalization,{});
 assert.ok(document.body.textContent.includes('Brak produktów dostępnych do personalizacji'));
 assert.equal(document.querySelector('input[type="file"]'),null);
 await reset();console.log('PASS independent inline store CTA, product title, 401 login roundtrip, null and empty catalog');
})().catch(error=>{console.error(error);process.exitCode=1;});
